/**
  * @brief 呼吸灯占空比更新处理（T02）
  *        基于 HAL_GetTick() 非阻塞软件调度：每 BREATH_STEP_MS 时间片
  *        将比较值 Pulse 步进 BREATH_PULSE_STEP，在 BREATH_PULSE_MIN~MAX
  *        （10%~90%）间往复变化，半程 40 步 x 25ms = 1s，全程约 2s。
  * @retval None
  */
static void Breath_Update(void)
{
  if ((HAL_GetTick() - g_breathLastTick) < BREATH_STEP_MS)
  {
    return;
  }
  g_breathLastTick = HAL_GetTick();

  /* 到达边界时反向 */
  if (g_breathPulse >= BREATH_PULSE_MAX)
  {
    g_breathDir = -1;
  }
  else if (g_breathPulse <= BREATH_PULSE_MIN)
  {
    g_breathDir = 1;
  }

  /* 更新比较值并写入 TIM2 通道 1，仅改变占空比，不影响 PWM 频率（Prescaler/Period 不变） */
  if (g_breathDir > 0)
  {
    g_breathPulse += BREATH_PULSE_STEP;
  }
  else
  {
    g_breathPulse -= BREATH_PULSE_STEP;
  }
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, g_breathPulse);
}
