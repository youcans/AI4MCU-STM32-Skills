/**
  * @brief  按键去抖处理：读取按键电平，仅在电平持续稳定超过去抖时长后更新稳定状态
  * @retval 稳定按键状态：0-松开，1-按下
  */
static uint8_t Button_Debounce(void)
{
  uint8_t raw = (uint8_t)(HAL_GPIO_ReadPin(USER_BTN_GPIO_Port, USER_BTN_Pin) == GPIO_PIN_SET);

  if (raw != button_stable_state)
  {
    /* 电平与稳定状态不一致：持续超过去抖时长才确认新状态 */
    if (HAL_GetTick() - button_state_tick >= BUTTON_DEBOUNCE_MS)
    {
      button_stable_state = raw;
      button_state_tick    = HAL_GetTick();
    }
  }
  else
  {
    /* 电平与稳定状态一致：刷新稳定计时起点 */
    button_state_tick = HAL_GetTick();
  }

  return button_stable_state;
}

